export const getIconByName = (name: string): Icon | null => {
  const found = availableIcons.find((i) => i.name === name);
  return found?.icon || null;
};

export const getIconsByCategory = (category: IconCategory): IconOption[] => {
  return availableIcons.filter((i) => i.category === category);
};

export const searchIcons = (query: string): IconOption[] => {
  const lowerQuery = query.toLowerCase();
  return availableIcons.filter(
    (i) =>
      i.name.toLowerCase().includes(lowerQuery) ||
      i.category.toLowerCase().includes(lowerQuery)
  );
};
